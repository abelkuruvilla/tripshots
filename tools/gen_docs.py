"""Regenerate the reference pages that come straight from the code:

    python tools/gen_docs.py          # writes docs/cli.md and docs/mcp-tools.md
    python tools/gen_docs.py --check  # exit 1 if they are out of date (CI runs this)
"""
from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path

os.environ["COLUMNS"] = "100"  # stable argparse wrapping
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

HEADER = "<!-- generated by tools/gen_docs.py: edit the code, then run `python tools/gen_docs.py` -->\n\n"


def cli_md() -> str:
    from tripshots.cli import build_parser
    p = build_parser()
    p.prog = "tripshots"
    sub = next(a for a in p._actions if a.__class__.__name__ == "_SubParsersAction")
    helps = {a.dest: a.help for a in sub._choices_actions}
    out = [HEADER, "# Command reference\n",
           "Every command prints its result as JSON on stdout and its progress on stderr, so scripts and agents "
           "can read the result directly. Running `tripshots` with no arguments opens [the app](app.md).\n",
           "| Command | What it does |", "|---|---|"]
    for name in sub.choices:
        out.append(f"| [`{name}`](#{name}) | {helps.get(name) or ''} |")
    out.append("")
    for name, sp in sub.choices.items():
        out += [f"## {name}\n", "```text", sp.format_help().replace(os.path.expanduser("~"), "~").rstrip(), "```\n"]
    return "\n".join(out)


def mcp_md() -> str:
    from tripshots import mcp_server
    tools = asyncio.run(mcp_server.mcp.list_tools())
    tools = tools.tools if hasattr(tools, "tools") else tools
    out = [HEADER, "# MCP tools\n",
           "What `tripshots mcp` offers an agent. Long-running tools (`find_footage`, `make_reel`, `render_reel`, "
           "`list_trips`, `people_discover`) start a background job, wait a while (about 50 s; `render_reel` 20 s), and otherwise return the job "
           "id to poll with `job_status`. See [AI agents](agents.md) for setup.\n",
           "## Server instructions\n", "Sent to the agent when it connects:\n", "```text",
           mcp_server.INSTRUCTIONS.strip(), "```\n"]
    for t in tools:
        schema = getattr(t, "inputSchema", None) or getattr(t, "input_schema", None) or {}
        props = schema.get("properties", {})
        req = set(schema.get("required", []))
        out.append(f"## {t.name}\n")
        out.append((t.description or "").strip() + "\n")
        if props:
            out += ["| Parameter | Type | Default |", "|---|---|---|"]
            for k, v in props.items():
                typ = v.get("type") or "/".join(x.get("type", "?") for x in v.get("anyOf", []) if x.get("type"))
                if v.get("items") and v["items"].get("type"):
                    typ += f" of {v['items']['type']}"
                dflt = "**required**" if k in req else json.dumps(v.get("default")) if "default" in v else ""
                out.append(f"| `{k}` | {typ} | {dflt} |")
            out.append("")
    return "\n".join(out)


def main() -> int:
    pages = {ROOT / "docs" / "cli.md": cli_md(), ROOT / "docs" / "mcp-tools.md": mcp_md()}
    if "--check" in sys.argv:
        stale = [p.name for p, text in pages.items() if not p.exists() or p.read_text() != text]
        if stale:
            print(f"out of date: {', '.join(stale)} (run python tools/gen_docs.py)")
            return 1
        print("docs up to date")
        return 0
    for p, text in pages.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
